// Сценарии обучающих роликов Maker.
// Шаг: say — что говорит Милена (и субтитр); do — JS в прототипе перед снимком; t — JS-выражение, которое
// возвращает элемент-цель (курсор и подсветка); click — показать клик; wait — пауза после do, мс.
// $(sel) и $$(sel) — доступны в do/t; txt(sel, text) — найти элемент по тексту.
module.exports = Object.assign(require('./steps_more.js'), {
  strat: {
    title: 'Стратегия', group: 'Запустить', client: 'Вита', next: 'Контент-план',
    intro: 'Стратегия. Что, кому и зачем говорим в соцсетях клиента.',
    steps: [
      { do: "go('strat');strSet('Вита')", t: "$('#str-body .bset-hd')",
        say: 'Стратегия — основа работы с клиентом: цель, аудитории, площадки и рубрики. Из неё собирается контент-план, а из плана — посты.' },
      { do: "", t: "txt('#v-strat .phead .pbtn','Рассказать о клиенте')", click: true,
        say: 'Чтобы собрать или дополнить стратегию, нажмите «Рассказать о клиенте».' },
      { do: "dockToggle(true);cpOpen('strat')", t: "$('#dcr-in')", wait: 900,
        say: 'Опишите клиента одним текстом: что продаёт, кому и чего хотим. Можно надиктовать голосом.' },
      { do: "var i=$('#dcr-in');i.value='Сеть клиник у дома. Хотим 150 записей на чекапы в месяц из соцсетей. Ведём VK и Telegram, пишем спокойно и на вы.';dcrSend()", t: "$('.dcr-card')", wait: 900,
        say: 'Maker понимает задачу и показывает, как сделает. Проверьте настройки и подтвердите.' },
      { do: "dcrCancel();dockToggle(false)", t: "txt('#str-body .panel h3','Рубрики').parentNode", wait: 700,
        say: 'Рубрики — постоянные темы клиента. Доли меняются кнопками плюс и минус.' },
      { do: "", t: "$('#str-body .phx')",
        say: 'Оранжевые плашки — то, чего Maker не знает. Он не выдумывает: впишите ответ, и он появится во всех материалах.' },
      { do: "", t: "$('#str-body .next-step')", click: true,
        say: 'Когда стратегия готова, отправьте её клиенту по ссылке или сразу собирайте контент-план.' }
    ]
  }
});
